primeiroNumero = float(input("Digite um numero: "))
segundoNumero = float(input("Digite outro numero: "))

#Adição
soma = primeiroNumero + segundoNumero
print(f"O resultado da soma de ({primeiroNumero} + {segundoNumero}) é : {soma}")

#Subtração
subtracao = primeiroNumero - segundoNumero
print(f"O resultado da subtração de ({primeiroNumero} - {segundoNumero}) é : {subtracao} ")

#Multiplicação
multip = primeiroNumero * segundoNumero
print(f"O resultado da multiplicação de ({primeiroNumero} * {segundoNumero}) é : {multip}")

#Divisão
divisão = primeiroNumero / segundoNumero
print(f"O resultado da divisão de ( {primeiroNumero} / {segundoNumero} é : {divisão}")

#resto (mod)
resto = primeiroNumero % segundoNumero
print(f"O resto da divisão de ({primeiroNumero} % {segundoNumero}) é : {resto}")



