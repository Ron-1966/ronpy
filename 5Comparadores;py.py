primeiroNumero = float(input("Digite um numero: "))
segundoNumero = float(input("Digite outro numero: "))

#Maior que
print(f"primeiro numero {primeiroNumero} >(maior que) segundo numero {segundoNumero} : {primeiroNumero > segundoNumero}")

#Menor que
print(f"primeiro numero {primeiroNumero} <(menor que) segundo numero {segundoNumero} : {primeiroNumero < segundoNumero}")

#maior ou igual
print(f"primeiro numero {primeiroNumero} >=(maior ou igual ao) segundo numero {segundoNumero} : {primeiroNumero >= segundoNumero}")

#Menor ou igual
print(f"primeiro numero {primeiroNumero} <=(menor ou igual ao) segundo numero {segundoNumero} : {primeiroNumero <= segundoNumero}")

#Igual
print(f"primeiro numero {primeiroNumero} ==(igual ao) segundo numero {segundoNumero} : {primeiroNumero == segundoNumero}")

#Diferente
print(f"primeiro numero {primeiroNumero} !=(diferente do) segundo numero {segundoNumero} : {primeiroNumero != segundoNumero}")